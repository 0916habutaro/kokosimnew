"""Stage43G-77: atomic school game pages for independently sealed fictional v2.

The legacy A archive is not an input. Pages come solely from the dedicated
v2 Option-A read API; neither records nor logical dates are converted.
"""
from __future__ import annotations

from pathlib import Path

PAGE_SIZE = 30
V2_SOURCE = "fictional_option_a_v2"


class CareerV2SchoolGamePager:
    """Bounded school/year/competition selection with fail-closed transitions."""

    source_kind = V2_SOURCE
    valid_verify_scopes = ("page", "selected_years")
    min_year = 10000
    max_year = None

    def __init__(self, v2_path: str | Path, calendar_path: str | Path,
                 school_id: str, selected_year: int,
                 *, index_path: str | Path | None = None):
        if (type(school_id) is not str or not school_id
                or type(selected_year) is not int or selected_year < 10000):
            raise ValueError("valid v2 school and game year are required")
        self.v2_path = Path(v2_path)
        self.calendar_path = Path(calendar_path)
        self.school_id = school_id
        # An index is never generated by browsing. Its presence alone does
        # not activate it: user selection must explicitly opt in.
        self.index_path = Path(index_path) if index_path is not None else None
        self.lookup_mode = "original_json1"
        self.century_index_paths: tuple[Path, ...] = ()
        self.start_year = selected_year
        self.end_year = selected_year
        self.competition_id: str | None = None
        self.verify_scope = "page"
        self.offset = 0
        self.page = self._fetch(
            selected_year, selected_year, None, 0, "page",
        )

    def _fetch(self, start: int, end: int, competition_id: str | None,
               offset: int, verify_scope: str,
               lookup_mode: str | None = None,
               index_path_override: Path | None = None,
               century_paths_override: tuple[Path, ...] | None = None) -> dict:
        mode = self.lookup_mode if lookup_mode is None else lookup_mode
        kwargs = dict(
            start_year=start, end_year=end, competition_id=competition_id,
            limit=PAGE_SIZE, offset=offset, verify_scope=verify_scope,
        )
        if mode == "original_json1":
            from .career_v2_school_game_page import read_v2_school_game_page
            data = read_v2_school_game_page(
                self.v2_path, self.calendar_path, self.school_id, **kwargs,
            )
            if data.get("school_filter_uses_unindexed_json_scan") is not True:
                raise ValueError("original v2 search source differs")
        elif mode == "separate_index":
            path = index_path_override or self.index_path
            if path is None:
                raise ValueError("derived school index path was not configured")
            from .career_v2_school_read_index import read_indexed_v2_school_page
            data = read_indexed_v2_school_page(
                self.v2_path, self.calendar_path, path,
                self.school_id, **kwargs,
            )
            if (data.get("uses_separate_verified_school_index") is not True
                    or data.get("derived_index_does_not_replace_source")
                    is not True
                    or data.get("school_filter_uses_unindexed_json_scan")
                    is not False):
                raise ValueError("derived school index source differs")
        elif mode == "century_shards":
            from .career_v2_school_century_shards import (
                read_v2_school_century_page,
            )
            paths = (self.century_index_paths if century_paths_override is None
                     else century_paths_override)
            if not paths:
                raise ValueError("no explicit cross-century index shards selected")
            data = read_v2_school_century_page(
                self.v2_path, self.calendar_path, paths,
                self.school_id, **kwargs,
            )
            if (data.get("cross_century_school_index_shards") is not True
                    or data.get("original_source_data_version_unchanged") is not True
                    or data.get("index_shards_generated_by_read") is not False):
                raise ValueError("cross-century source provenance differs")
        else:
            raise ValueError("unknown fictional-v2 lookup selection")
        if (data.get("school_id") != self.school_id
                or data.get("start_year") != start
                or data.get("end_year") != end
                or data.get("competition_id") != competition_id
                or data.get("limit") != PAGE_SIZE
                or data.get("offset") != offset
                or data.get("verification_scope") != verify_scope
                or data.get("legacy_records_combined") is not False
                or data.get("source_records_not_modified") is not True
                or data.get("visible_match_checksums_verified") is not True
                or data.get("all_selected_year_payloads_verified")
                is not (verify_scope == "selected_years")):
            raise ValueError("fictional v2 search did not verify its saved source")
        for row in data["records"]:
            if (row.get("stored_source") !=
                    "explicit_fictional_v2_option_a_not_official"
                    or row.get("school_id") != self.school_id
                    or type(row.get("game_day_token")) is not str):
                raise ValueError("fictional v2 game row has wrong provenance")
        return data

    def available_index_versions(self) -> tuple[str, ...]:
        """List names only; enumeration cannot enable an index."""
        from .career_v2_school_index_versions import (
            list_v2_school_index_versions,
        )
        return list_v2_school_index_versions(
            self.v2_path, self.calendar_path,
        )

    def select_index_version(self, filename: str) -> dict:
        """Select a strictly verified slot-local index without fallback.

        Even when the index is already active, its replacement is staged
        and re-read under the current filters and pagination position
        before committing any part of the selection.
        """
        from .career_v2_school_index_versions import (
            verify_v2_school_index_version,
        )
        candidate = verify_v2_school_index_version(
            self.v2_path, self.calendar_path, filename,
        )
        candidate_path = Path(candidate["path"])
        if self.lookup_mode == "separate_index":
            data = self._fetch(
                self.start_year, self.end_year, self.competition_id,
                self.offset, self.verify_scope, lookup_mode="separate_index",
                index_path_override=candidate_path,
            )
            if self.offset and not data["records"]:
                raise ValueError("selected version has no current game page")
        else:
            data = self.page
        self.index_path = candidate_path
        self.page = data
        return candidate

    def select_century_shards(self, filenames: tuple[str, ...] | list[str]) -> dict:
        """Explicitly verify named slot-local indexes then atomically activate.

        Names are not paths; we do not scan the directory, create shards,
        switch save slots, or infer missing coverage. Even if the UI was
        previously using another backend it is unchanged on failure.
        """
        import re

        from .career_v2_school_century_shards import MAX_SHARDS_PER_REQUEST
        if (not isinstance(filenames, (tuple, list))
                or not 1 <= len(filenames) <= MAX_SHARDS_PER_REQUEST):
            raise ValueError("select 1..32 explicit century index filenames")
        name_rule = re.compile(
            r"fictional_v2_school_read_index_G[0-9]+_G[0-9]+"
            r"(?:_[A-Za-z0-9_-]+)?\.sqlite3\Z"
        )
        paths = []
        slot = self.v2_path.resolve().parent
        if self.calendar_path.resolve().parent != slot:
            raise ValueError("calendar is not within this saved slot")
        for name in filenames:
            if type(name) is not str or name_rule.fullmatch(name) is None:
                raise ValueError("century index filename is not allowed")
            path = slot / name
            if path.is_symlink() or not path.is_file():
                raise ValueError("century index is missing or a symbolic link")
            paths.append(path)
        if len(set(paths)) != len(paths):
            raise ValueError("duplicate century index filenames")

        candidate_paths = tuple(paths)
        # A manual activation always audits the requested full time window,
        # not just the 30 visible rows.
        proof = self._fetch(
            self.start_year, self.end_year, self.competition_id,
            self.offset, "selected_years", lookup_mode="century_shards",
            century_paths_override=candidate_paths,
        )
        if not proof.get("offpage_derived_memberships_verified"):
            raise ValueError("full-century index source proof was not completed")
        if self.verify_scope == "selected_years":
            data = proof
        else:
            data = self._fetch(
                self.start_year, self.end_year, self.competition_id,
                self.offset, self.verify_scope, lookup_mode="century_shards",
                century_paths_override=candidate_paths,
            )
        if self.offset and not data["records"]:
            raise ValueError("no verified page at this cross-century offset")
        self.century_index_paths = candidate_paths
        self.lookup_mode, self.page = "century_shards", data
        return data

    def select_lookup(self, mode: str) -> dict:
        """Switch read backend only after verifying the selected saved page.

        No automatic fallback: an absent, stale or tampered index causes
        failure, leaving the previous verified mode/page/filters intact.
        """
        if type(mode) is not str or mode not in (
            "original_json1", "separate_index", "century_shards",
        ):
            raise ValueError("unknown fictional-v2 lookup selection")
        if mode == self.lookup_mode:
            return self.page
        data = self._fetch(
            self.start_year, self.end_year, self.competition_id,
            self.offset, self.verify_scope, lookup_mode=mode,
        )
        if not data["records"] and self.offset:
            raise ValueError("selected indexed game page no longer exists")
        self.lookup_mode, self.page = mode, data
        return data

    def apply_filters(self, start: int, end: int,
                      competition_id: str | None = None,
                      verify_scope: str = "page") -> dict:
        data = self._fetch(start, end, competition_id, 0, verify_scope)
        self.start_year, self.end_year = start, end
        self.competition_id, self.verify_scope = competition_id, verify_scope
        self.offset, self.page = 0, data
        return data

    def move(self, direction: int) -> dict:
        if type(direction) is not int or direction not in (-1, 1):
            raise ValueError("invalid game page direction")
        target = self.offset + direction * PAGE_SIZE
        if target < 0 or target >= self.page["total"]:
            return self.page
        data = self._fetch(
            self.start_year, self.end_year, self.competition_id,
            target, self.verify_scope,
        )
        if not data["records"]:
            raise ValueError("fictional v2 page changed while browsing")
        self.offset, self.page = target, data
        return data

    @property
    def can_previous(self) -> bool:
        return self.offset > 0

    @property
    def can_next(self) -> bool:
        return self.offset + PAGE_SIZE < self.page["total"]
